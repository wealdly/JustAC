"""Every rank of every learnable ability of a class, from the client spell tables, written
into a simulator checkout as sim/<class>/level_ranks_generated.go.

    python tools/forever-sim-patches/gen_class_ranks.py --sim <simulator checkout> [--class rogue,druid,hunter,warlock]

The simulator defines some classes' abilities only at levels 25, 40, 50 and 60. With these
tables the class code can pick the rank a character of any level has (core.RankAtLevel) and
read that rank's own spell id, cost, duration and effect points. The data is the project's
client CSV set (Documentation/wow_spell_csv_forever), the same the generators use.

Fields per rank: the spell id, the level it is learned at, power cost (flat and percent of base),
cast time, duration, cooldown (all ms) and up to three effects: effect and aura type, base
points, points per level, points per resource (combo point), spell power coefficient, variance
and aura period (ms). The client's base points are the value shown in the tooltip's low end;
nothing server-side (attack power coefficients, threat) is in here.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import check_forever_apl as cfa  # noqa: E402

DEFAULT = "rogue,druid,hunter,warlock,mage,priest,shaman,paladin,warrior"


def num(value):
    try:
        return float(value or 0)
    except ValueError:
        return 0.0


def fmt(value):
    return ("%.6f" % value).rstrip("0").rstrip(".") or "0"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sim", required=True)
    ap.add_argument("--class", dest="classes", default=DEFAULT)
    args = ap.parse_args()

    learn, max_level = {}, {}
    for r in cfa.rows("SpellLevels"):
        if r["DifficultyID"] == "0":
            learn[r["SpellID"]] = int(num(r["SpellLevel"]) or num(r["BaseLevel"]))
            max_level[r["SpellID"]] = int(num(r["MaxLevel"]))
    misc = {r["SpellID"]: r for r in cfa.rows("SpellMisc") if r["DifficultyID"] == "0"}
    durations = {r["ID"]: int(num(r["Duration"])) for r in cfa.rows("SpellDuration")}
    casts = {r["ID"]: int(num(r["Base"])) for r in cfa.rows("SpellCastTimes")}
    cooldowns = {}
    for r in cfa.rows("SpellCooldowns"):
        if r["DifficultyID"] == "0":
            cooldowns[r["SpellID"]] = int(max(num(r["RecoveryTime"]), num(r["CategoryRecoveryTime"])))
    power = {}
    for r in sorted(cfa.rows("SpellPower"), key=lambda r: int(r["OrderIndex"] or 0), reverse=True):
        power[r["SpellID"]] = (num(r["ManaCost"]), num(r["PowerCostPct"]), int(num(r["PowerType"])))
    effects = {}
    for r in cfa.rows("SpellEffect"):
        if r["DifficultyID"] == "0" and int(r["EffectIndex"] or 0) < 3:
            effects.setdefault(r["SpellID"], {})[int(r["EffectIndex"] or 0)] = r

    for cls in [c.strip() for c in args.classes.split(",") if c.strip()]:
        chains, _ = cfa.class_chains(cfa.CLASS_MASK[cls])
        out = ["// Code generated by JustAC tools/forever-sim-patches/gen_class_ranks.py. DO NOT EDIT.",
               "// LOCAL ADDITION: every rank of every learnable %s ability, from the client spell tables." % cls,
               "", "package %s" % cls, "", 'import "github.com/wowsims/classic/sim/core"', "",
               "// levelRanks: ability slug -> its ranks in learn order.",
               "var levelRanks = map[string][]core.SpellRank{"]
        for slug_name in sorted(chains):
            rows = []
            for sid, _ in chains[slug_name]:
                m = misc.get(sid, {})
                cost, pct, ptype = power.get(sid, (0.0, 0.0, 0))
                effs = []
                for i in range(3):
                    e = effects.get(sid, {}).get(i)
                    if not e:
                        effs.append("{}")
                        continue
                    effs.append("{Effect: %d, Aura: %d, BasePoints: %s, PerLevel: %s, PerResource: %s, Coefficient: %s, "
                                "Variance: %s, PeriodMs: %d}" % (
                                    int(num(e["Effect"])), int(num(e["EffectAura"])), fmt(num(e["EffectBasePointsF"])),
                                    fmt(num(e["EffectRealPointsPerLevel"])), fmt(num(e["EffectPointsPerResource"])),
                                    fmt(num(e["EffectBonusCoefficient"])), fmt(num(e["Variance"])),
                                    int(num(e["EffectAuraPeriod"]))))
                rows.append((learn.get(sid, 0), int(sid),
                             "\t\t{SpellID: %s, Level: %d, MaxLevel: %d, Cost: %s, CostPct: %s, PowerType: %d, CastMs: %d, "
                             "DurationMs: %d, CooldownMs: %d, Effects: [3]core.RankEffect{%s}}," % (
                                 sid, learn.get(sid, 0), max_level.get(sid, 0), fmt(cost), fmt(pct), ptype,
                                 casts.get(m.get("CastingTimeIndex", ""), 0), durations.get(m.get("DurationIndex", ""), 0),
                                 cooldowns.get(sid, 0), ", ".join(effs))))
            out.append('\t"%s": {' % slug_name)
            out.extend(text for _, _, text in sorted(rows))
            out.append("\t},")
        out += ["}", "",
                "// rankFor is the rank of an ability a character of this level has, or nil before its first rank.",
                "func rankFor(slug string, level int32) *core.SpellRank {",
                "\treturn core.RankAtLevel(levelRanks[slug], level)", "}", ""]
        path = os.path.join(args.sim, "sim", cls, "level_ranks_generated.go")
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(out))
        print("wrote %s: %d abilities" % (path, len(chains)))


if __name__ == "__main__":
    main()
