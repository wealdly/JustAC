"""Per-level pet stats from a Classic server database, written into a simulator checkout as
sim/core/pet_levelstats_generated.go.

    python tools/forever-sim-patches/gen_pet_levelstats.py --sim <simulator checkout> --db <mangos.sqlite>

Source: the `pet_levelstats` table of the vmangos world database (https://github.com/vmangos/core,
GPL-2.0), as a SQLite dump. It is server data, not in the game client. Entry 1 is the hunter pet;
416, 417, 1860 and 1863 are the warlock's imp, felhunter, voidwalker and succubus. The
simulator's own level 60 hunter pet (strength 136, agility 100, intellect 50, spirit 80) and its
demon rows at 25, 40, 50 and 60 equal this table's rows, so the table is what those came from
and its other levels are the same data, not an assumption. Whether WoW Forever changed the
curve is not known: nothing in game has been measured.

The generated file holds data from a GPL-2.0 database and stays in the local simulator checkout;
it is not part of this project's patch file.
"""
import argparse
import os
import sqlite3

ENTRIES = {1: "hunter pet", 416: "imp", 417: "felhunter", 1860: "voidwalker", 1863: "succubus"}
FIELDS = ("health", "mana", "armor", "strength", "agility", "stamina", "intellect", "spirit")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sim", required=True)
    ap.add_argument("--db", required=True, help="vmangos world database as SQLite")
    args = ap.parse_args()
    db = sqlite3.connect(args.db)
    out = ["// Code generated by JustAC tools/forever-sim-patches/gen_pet_levelstats.py. DO NOT EDIT.",
           "// LOCAL ADDITION: per-level pet stats, vmangos world database table pet_levelstats (GPL-2.0).",
           "", "package core", "",
           "// PetLevelStat is a pet's own stats at one level.",
           "type PetLevelStat struct {",
           "\tHealth, Mana, Armor, Strength, Agility, Stamina, Intellect, Spirit float64", "}", "",
           "// ClassicPetLevelStats: creature entry -> stats by level (index 0 unused). Entry 1 is the",
           "// hunter pet; 416, 417, 1860 and 1863 are the imp, felhunter, voidwalker and succubus.",
           "var ClassicPetLevelStats = map[int32][]PetLevelStat{"]
    for entry in sorted(ENTRIES):
        rows = dict((r[0], r[1:]) for r in db.execute(
            "select level, %s from pet_levelstats where entry = ? order by level" % ", ".join(FIELDS), (entry,)))
        assert rows and min(rows) == 1, (entry, len(rows))
        out.append("\t%d: { // %s" % (entry, ENTRIES[entry]))
        out.append("\t\t{},")
        for level in range(1, max(rows) + 1):
            out.append("\t\t{%s}, // %d" % (", ".join("%g" % v for v in rows[level]), level))
        out.append("\t},")
    out += ["}", "",
            "// PetLevelRatio is how much of its value at anchorLevel a pet stat has at level, by the Classic",
            "// table: pick(row at level) / pick(row at anchorLevel). 1 when the table has no such rows.",
            "func PetLevelRatio(entry int32, level int32, anchorLevel int32, pick func(PetLevelStat) float64) float64 {",
            "\trows := ClassicPetLevelStats[entry]",
            "\tif level < 1 || anchorLevel < 1 || int(level) >= len(rows) || int(anchorLevel) >= len(rows) {",
            "\t\treturn 1", "\t}",
            "\tanchor := pick(rows[anchorLevel])",
            "\tif anchor == 0 {", "\t\treturn 1", "\t}",
            "\treturn pick(rows[level]) / anchor", "}", ""]
    path = os.path.join(args.sim, "sim", "core", "pet_levelstats_generated.go")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
